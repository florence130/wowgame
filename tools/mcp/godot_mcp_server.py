"""wowgame Godot MCP server (stdio).

Lets an MCP client (Claude Desktop / Cowork / Claude Code) drive the LOCAL Godot 4.7.2 + Blender
for the E:\\wowgame project: script checks, automated tests, zone regeneration, game / UI / model
screenshots, Blender model builds, and file access restricted to the project folder.

Run:  python tools/mcp/godot_mcp_server.py
"""
import os
import glob
import subprocess
import time
from mcp.server.fastmcp import FastMCP, Image

PROJECT = r"E:\wowgame"
GODOT = r"F:\Godot_v4.7.2-stable_mono_win64\Godot_v4.7.2-stable_mono_win64_console.exe"
GODOT_GUI = r"F:\Godot_v4.7.2-stable_mono_win64\Godot_v4.7.2-stable_mono_win64.exe"
BLENDER = r"E:\SteamLibrary\steamapps\common\Blender\blender.exe"
SHOTS = os.path.join(PROJECT, ".shots")
MODELS = os.path.join(PROJECT, "assets", "models")
NOWIN = 0x08000000  # CREATE_NO_WINDOW

mcp = FastMCP("wowgame-godot", instructions=(
    "Tools for the wowgame Godot project at E:\\wowgame (Godot 4.7.2, GDScript). "
    "Read CLAUDE.md and PROJECT_STATE.md first. Always run check_scripts after editing .gd files — a parse error "
    "makes the game hang. Zone scenes are GENERATED by tools/gen_*.gd: edit the generators then call regenerate_zones, "
    "never hand-edit scenes/zones/*.tscn. Building/prop models are GENERATED by tools/blender/*.py: edit those scripts, "
    "then call blender_build and blender_preview, then regenerate_zones. UI code lives in src/ui/. "
    "Use ui_screenshots / tour_screenshots to verify visually."))


def _run(args, timeout, cwd=PROJECT):
    t0 = time.time()
    try:
        p = subprocess.run(args, cwd=cwd, capture_output=True, timeout=timeout, creationflags=NOWIN)
        out = (p.stdout or b"").decode("utf-8", "replace") + (p.stderr or b"").decode("utf-8", "replace")
        code = p.returncode
    except subprocess.TimeoutExpired as e:
        out = ((e.stdout or b"").decode("utf-8", "replace") if e.stdout else "") + "\n[TIMEOUT after %ds]" % timeout
        code = -1
    return code, out, time.time() - t0


def _filter(out, keep=("PASS", "FAIL", "RESULT", "DONE", "PORTAL", "SCRIPT ERROR", "Parse Error", "Compile Error",
                       "CHECKED", "FAILED", "saved", "SHOT", "ERROR:", "[world]", "HP ", "WARNING")):
    lines = [l for l in out.splitlines() if any(k in l for k in keep) and "leaked" not in l and "resources still" not in l]
    return "\n".join(lines[-200:])


def _safe(path):
    full = os.path.abspath(os.path.join(PROJECT, path))
    if not full.lower().startswith(PROJECT.lower()):
        raise ValueError("path must stay inside E:\\wowgame")
    return full


def _images(files, limit):
    out = []
    for f in files[:limit]:
        with open(f, "rb") as fh:
            out.append(Image(data=fh.read(), format="png"))
    return out


# ---------------------------------------------------------------- project / files
@mcp.tool()
def project_info() -> str:
    """Paths, engine versions and the key docs to read first."""
    _, v, _ = _run([GODOT, "--version"], 60)
    return ("project: %s\ngodot: %s (%s)\nblender: %s\nshots dir: %s\n"
            "read first: CLAUDE.md, PROJECT_STATE.md (section 5 = commands, section 6 = art pipeline)\n"
            "zone generators: tools/gen_vale.gd, tools/gen_tidewind.gd, tools/gen_solenne.gd (city), tools/gen_sanctum.gd\n"
            "model scripts: tools/blender/build_models.py, build_props.py, build_landmarks.py; game wrapper src/world/model_prop.gd\n"
            "UI: src/ui/ (ui_theme.gd, ui_fx.gd, hud.gd, win_*.gd)" % (PROJECT, GODOT, v.strip(), BLENDER, SHOTS))


@mcp.tool()
def list_files(pattern: str = "src/**/*.gd") -> str:
    """Glob files inside the project (e.g. 'src/ui/*.gd', 'tools/blender/*.py')."""
    files = glob.glob(_safe(pattern), recursive=True)
    return "\n".join(os.path.relpath(f, PROJECT) for f in sorted(files)[:500])


@mcp.tool()
def read_file(path: str) -> str:
    """Read a UTF-8 text file inside the project (path relative to E:\\wowgame)."""
    with open(_safe(path), "r", encoding="utf-8") as fh:
        return fh.read()


@mcp.tool()
def write_file(path: str, content: str) -> str:
    """Create/overwrite a UTF-8 text file inside the project (path relative to E:\\wowgame)."""
    full = _safe(path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(content)
    return "wrote %s (%d chars)" % (path, len(content))


@mcp.tool()
def replace_in_file(path: str, old: str, new: str) -> str:
    """Replace one exact, unique occurrence of `old` with `new` in a project file."""
    full = _safe(path)
    with open(full, "r", encoding="utf-8") as fh:
        text = fh.read()
    n = text.count(old)
    if n != 1:
        return "ERROR: expected exactly 1 occurrence, found %d" % n
    with open(full, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text.replace(old, new))
    return "replaced in %s" % path


# ---------------------------------------------------------------- godot
@mcp.tool()
def check_scripts() -> str:
    """Re-import the project and load every .gd file; reports parse/compile errors. Run after every code edit."""
    _run([GODOT, "--headless", "--path", PROJECT, "--import"], 600)
    code, out, dt = _run([GODOT, "--headless", "--path", PROJECT, "res://tests/check.tscn"], 300)
    return _filter(out, ("CHECKED", "FAILED", "SCRIPT ERROR", "Parse Error", "Compile Error", "at: GDScript")) + "\n(%.0fs)" % dt


@mcp.tool()
def run_test(mode: str = "basic", timeout: int = 600) -> str:
    """Run an in-game automated test (opens a game window). mode: basic | services | crafting | dungeon | portal.
    Returns PASS/FAIL lines. Runs check_scripts first and aborts on errors."""
    chk = check_scripts()
    if "failed 0" not in chk:
        return "SCRIPT CHECK FAILED — fix first:\n" + chk
    args = [GODOT, "--path", PROJECT, "res://tests/autotest.tscn", "--", "out=%s/.shots/%s" % (PROJECT, mode)]
    if mode != "basic":
        args.insert(4, "mode=%s" % mode)
    code, out, dt = _run(args, timeout)
    return _filter(out) + "\n(%.0fs)" % dt


@mcp.tool()
def regenerate_zones(zones: str = "") -> str:
    """Rebuild zone scenes from the generators. zones: comma list of vale,tidewind,sanctum (empty = all).
    tidewind includes the city 晴岚港. sanctum must be generated before tidewind (all = correct order)."""
    _run([GODOT, "--headless", "--path", PROJECT, "--import"], 600)
    args = [GODOT, "--headless", "--path", PROJECT, "res://tools/gen.tscn", "--"] + [z.strip() for z in zones.split(",") if z.strip()]
    code, out, dt = _run(args, 900)
    return _filter(out, ("saved", "done", "SCRIPT ERROR", "Parse Error", "ERROR:")) + "\n(%.0fs)" % dt


def _shots(sub):
    return sorted(glob.glob(os.path.join(SHOTS, sub, "*.png")))


@mcp.tool()
def ui_screenshots(windows: str = "hud,bag,char,dungeon,prof,auction", npc: str = "", max_images: int = 6) -> list:
    """Start the game in the city and screenshot UI windows. windows: comma list of
    hud,bag,char,spells,quests,map,menu,dungeon,prof,bank,transmog,auction,npc (npc = dialog of `npc` id, e.g. mayor)."""
    chk = check_scripts()
    if "failed 0" not in chk:
        return ["SCRIPT CHECK FAILED:\n" + chk]
    d = os.path.join(SHOTS, "ui")
    for f in _shots("ui"):
        os.remove(f)
    args = [GODOT, "--path", PROJECT, "res://tests/autotest.tscn", "--", "mode=ui", "windows=" + windows, "out=" + d.replace("\\", "/")]
    if npc:
        args.append("npc=" + npc)
    code, out, dt = _run(args, 400)
    files = _shots("ui")
    return [_filter(out) + "\nfiles:\n" + "\n".join(files)] + _images(files, max_images)


@mcp.tool()
def tour_screenshots(zone: str = "city", only: str = "", max_images: int = 6) -> list:
    """Fly the camera through preset viewpoints and screenshot. zone: city | vale | tidewind | sanctum.
    only: optional comma filter of viewpoint names (e.g. 'plaza,market'). Viewpoints are in tests/autotest.gd TOURS."""
    d = os.path.join(SHOTS, "tour_" + zone)
    for f in _shots("tour_" + zone):
        os.remove(f)
    code, out, dt = _run([GODOT, "--path", PROJECT, "res://tests/autotest.tscn", "--", "mode=tour", "zone=" + zone,
                          "out=" + d.replace("\\", "/")], 900)
    files = _shots("tour_" + zone)
    if only:
        keys = [k.strip() for k in only.split(",")]
        files = [f for f in files if any(("_" + k + ".png") in f for k in keys)]
    return [_filter(out) + "\nfiles:\n" + "\n".join(files)] + _images(files, max_images)


@mcp.tool()
def view_image(path: str) -> list:
    """Return a PNG inside the project (e.g. a file listed by a screenshot tool) as an image."""
    return _images([_safe(path)], 1)


@mcp.tool()
def open_editor() -> str:
    """Launch the Godot editor on this project (does not wait)."""
    subprocess.Popen([GODOT_GUI, "--editor", "--path", PROJECT], cwd=PROJECT)
    return "Godot editor launching"


@mcp.tool()
def run_game() -> str:
    """Launch the game normally (main menu) for manual play; does not wait."""
    subprocess.Popen([GODOT_GUI, "--path", PROJECT], cwd=PROJECT)
    return "game launching"


# ---------------------------------------------------------------- blender
SCRIPTS = {"models": "build_models.py", "props": "build_props.py", "landmarks": "build_landmarks.py"}


@mcp.tool()
def blender_build(batch: str = "models", names: str = "") -> str:
    """Rebuild GLB models in background Blender. batch: models | props | landmarks (tools/blender/build_<batch>.py).
    names: comma list like 'rowhouse_1,house_0' (empty = whole batch). Then call regenerate_zones to use them."""
    script = os.path.join(PROJECT, "tools", "blender", SCRIPTS.get(batch, batch))
    code, out, dt = _run([BLENDER, "-b", "--factory-startup", "--python", script, "--", MODELS, names], 900)
    keep = [l for l in out.splitlines() if "EXPORTED" in l or "MODELS DONE" in l or "Error" in l or "Traceback" in l or 'File "' in l]
    return "\n".join(keep[-120:]) + "\n(%.0fs)" % dt


@mcp.tool()
def blender_preview(names: str, max_images: int = 6) -> list:
    """Render 3/4 preview images of models (comma list of GLB names, e.g. 'rowhouse_1,fountain_0')."""
    script = os.path.join(PROJECT, "tools", "blender", "preview_models.py")
    _run([BLENDER, "-b", "--factory-startup", "--python", script, "--", MODELS, names], 600)
    files = [os.path.join(MODELS, "_preview", n.strip() + ".png") for n in names.split(",") if n.strip()]
    files = [f for f in files if os.path.exists(f)]
    return ["files:\n" + "\n".join(files)] + _images(files, max_images)


@mcp.tool()
def list_models() -> str:
    """List exported GLB models and their nominal sizes [width, height, depth]."""
    import json
    with open(os.path.join(MODELS, "models.json"), encoding="utf-8") as fh:
        d = json.load(fh)
    return "\n".join("%s %s" % (k, v) for k, v in sorted(d.items()))


if __name__ == "__main__":
    mcp.run()
